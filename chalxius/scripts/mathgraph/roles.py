def allowed_commands(role: str) -> set[str]:
    # Fail closed: an unknown role gets no project capability.
    return set(ROLE_COMMANDS.get(role, set()))


def allowed_commands_for_workflow(
    role: str,
    workflow_evidence_version: int,
) -> set[str]:
    commands = allowed_commands(role)
    if role == "worker" and workflow_evidence_version >= 5:
        return commands.intersection(V5_WORKER_COMMANDS)
    if role == "worker" and workflow_evidence_version == 4:
        return commands.intersection(V4_WORKER_COMMANDS)
    if role == "host" and workflow_evidence_version >= 5:
        return commands.intersection(V5_HOST_COMMANDS)
    if role == "host" and workflow_evidence_version == 4:
        return commands.intersection(V4_HOST_COMMANDS)
    return commands


def allowed_bound_worker_queries_for_workflow(
    role: str,
    workflow_evidence_version: int,
) -> set[str]:
    """Return exact-id queries that require a separately validated task card."""

    if role == "worker" and workflow_evidence_version >= 4:
        return set(V4_BOUND_WORKER_QUERY_COMMANDS)
    return set()
